#!/usr/bin/env python3
"""Build every reviewer from its one spec in testing/reviewers/.

Each spec becomes:
  .claude/agents/<name>.md          Claude Code subagent (kind: reviewer; also one-shot persona agents)
  .claude/commands/<name>.md        Claude Code slash command (kind: roleplay, interactive)
  testing/prompts/paste/<name>.md   paste-ready prompt for ChatGPT / PromptLab / any chat box

Kinds:
  reviewer   critic agent (hostile-judge, data-critic, test-breaker)
  roleplay   interactive persona: slash command + paste prompt, AND a one-shot agent (persona-<x>)
  persona    one-shot persona only: agent + paste prompt (no interactive command)
A subagent cannot hold a dialogue, so persona agents read the material once and report in character.

Edit the spec, never the generated files. Run from anywhere: python3 testing/build_reviewers.py
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent  # Finalists/
SPECS = HERE / "reviewers"
AGENTS = ROOT / ".claude" / "agents"
COMMANDS = ROOT / ".claude" / "commands"
PASTE = HERE / "prompts" / "paste"
OC_AGENTS = ROOT / ".opencode" / "agents"
OC_COMMANDS = ROOT / ".opencode" / "commands"

HEADER = "<!-- Generated by testing/build_reviewers.py from testing/reviewers/{src}. Edit the spec, not this file. -->\n"

ONESHOT_RULES = """Rules for you:
- This is a one-shot review. No one will answer you, so do not ask questions and do not wait. Where you would ask, write it as a question you would put to the team.
- Stay in character. Be realistic, not polite. Judge only the material and the context. Do not invent facts about our work, data or results; if something is not shown, say you cannot tell.
- Raise at least five specific objections or confusions, each tied to something in the material.
- You are a simulated persona, not a real user. Never present your reactions as evidence that real users said or did anything.

Output, in this order, and nothing else:
1. First reaction in character, under 150 words, first person.
2. Findings table: # | where in the material (quote at most 12 words) | what was unclear, wrong or missing | type (framing, missing requirement, confusing output, trust, privacy or security, cost, next step) | severity (high, medium, low) | suggested fix.
3. The questions you would put to the team, hardest first (up to 6).
4. Anything you needed that is not shown.
5. Whether you could state the next step after reading it: yes or no, and what it was.
Save the full output to testing/transcripts/NN_{name}_YYYYMMDD.md if you can write files; otherwise end with "Save this to testing/transcripts/".
"""

PASTE_FOOTER = """
---
TEAM CONTEXT (paste the contents of testing/context.md here):


MATERIAL (paste the file or text to {verb} here):

"""


def parse(path):
    text = path.read_text()
    _, fm, body = text.split("---\n", 2)
    meta = {}
    for line in fm.strip().splitlines():
        k, v = line.split(":", 1)
        meta[k.strip()] = v.strip()
    return meta, body.strip() + "\n"


def main():
    for d in (AGENTS, COMMANDS, PASTE, OC_AGENTS, OC_COMMANDS):
        d.mkdir(parents=True, exist_ok=True)
    for spec in sorted(SPECS.glob("*.md")):
        meta, body = parse(spec)
        name, kind = meta["name"], meta["kind"]
        src = spec.name
        verb = "review" if kind in ("reviewer", "persona") else "present"

        read_ctx = "First read `testing/context.md` and every file it names. Do not start until you have."
        material_cc = "the file or text the user names when they invoke you (if none, ask which file)"
        material_cmd = "$ARGUMENTS (a file path or a short description; if empty, ask me what I am showing you)"

        def oneshot_body(read_text, material_text):
            role = body.split("<<READ_CONTEXT>>")[0].strip()
            return (role + "\n\n" + read_text + "\n\nMaterial you are shown: " + material_text + "\n\n"
                    + ONESHOT_RULES.format(name=name.replace("-", "_")))

        if kind == "reviewer":
            agent_body = body.replace("<<READ_CONTEXT>>", read_ctx).replace("<<MATERIAL>>", material_cc)
            front = (f"---\nname: {meta['name']}\ndescription: {meta['description']}\n"
                     f"tools: {meta['tools']}\nmodel: inherit\n---\n")
            (AGENTS / f"{name}.md").write_text(front + HEADER.format(src=src) + "\n" + agent_body)
            ocf = (f"---\ndescription: {meta['description']}\nmode: subagent\n"
                   f"permission:\n  edit: ask\n  bash: deny\n---\n")
            (OC_AGENTS / f"{name}.md").write_text(ocf + HEADER.format(src=src) + "\n" + agent_body)
        else:
            if kind == "roleplay":
                cmd_body = body.replace("<<READ_CONTEXT>>", read_ctx).replace("<<MATERIAL>>", material_cmd)
                front = (f"---\ndescription: {meta['description']}\nargument-hint: [file or note you are presenting]\n"
                         f"allowed-tools: {meta['tools']}\n---\n")
                (COMMANDS / f"{name}.md").write_text(front + HEADER.format(src=src) + "\n" + cmd_body)
                (OC_COMMANDS / f"{name}.md").write_text(f"---\ndescription: {meta['description']}\n---\n" + HEADER.format(src=src) + "\n" + cmd_body)
                agent_desc = (f"One-shot, in-character review by the {name} persona of the file or text you name (no dialogue). "
                              f"For the interactive meeting use /{name}.")
            else:  # persona
                agent_desc = meta["description"]
            agent_name = name.replace("_", "-")
            agent_body = oneshot_body(read_ctx, material_cc)
            front = (f"---\nname: {agent_name}\ndescription: {agent_desc}\n"
                     f"tools: {meta['tools']}\nmodel: inherit\n---\n")
            (AGENTS / f"{agent_name}.md").write_text(front + HEADER.format(src=src) + "\n" + agent_body)
            ocf = (f"---\ndescription: {agent_desc}\nmode: subagent\n"
                   f"permission:\n  edit: ask\n  bash: deny\n---\n")
            (OC_AGENTS / f"{agent_name}.md").write_text(ocf + HEADER.format(src=src) + "\n" + agent_body)

        # Any chat box: context and material are pasted under the prompt.
        paste_read = "The team's context is pasted below under TEAM CONTEXT. Use it as the only source of facts about the project."
        paste_mat = "pasted below under MATERIAL"
        if kind == "persona":
            paste_body = oneshot_body(paste_read, paste_mat)
        else:
            paste_body = body.replace("<<READ_CONTEXT>>", paste_read).replace("<<MATERIAL>>", paste_mat)
        (PASTE / f"{name}.md").write_text(HEADER.format(src=src) + "\n" + paste_body + PASTE_FOOTER.format(verb=verb))
        print(f"built {name} ({kind})")
    # Hand-written commands (not from specs): copy to OpenCode, dropping Claude-only keys.
    for c in ("kickoff", "checkpoint"):
        t = (COMMANDS / f"{c}.md").read_text()
        _, fm, body = t.split("---\n", 2)
        desc = next(l for l in fm.splitlines() if l.startswith("description:"))
        (OC_COMMANDS / f"{c}.md").write_text(f"---\n{desc}\n---\n{body}")
        print(f"copied {c} -> .opencode/commands")


if __name__ == "__main__":
    main()
