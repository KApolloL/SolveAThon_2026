#!/usr/bin/env python3
"""Build every reviewer and persona from its one spec in testing/reviewers/.

Each spec becomes:
  .claude/agents/<name>.md          Claude Code subagent (reviewer and persona)
  .claude/commands/<name>.md        Claude Code slash command (persona only, interactive)
  .opencode/agents/<name>.md        OpenCode subagent (reviewer and persona)
  .opencode/commands/<name>.md      OpenCode slash command (persona only, interactive)
  testing/prompts/paste/<name>.md   paste-ready prompt for ChatGPT / PromptLab / any chat box

A persona subagent is one-shot: it role-plays from the material it is given and
returns the observer report. The slash command stays interactive and waits for END.

Edit the spec, never the generated files. Run from anywhere:
  python3 testing/build_reviewers.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent  # Finalists/
SPECS = HERE / "reviewers"
AGENTS = ROOT / ".claude" / "agents"
COMMANDS = ROOT / ".claude" / "commands"
PASTE = HERE / "prompts" / "paste"
OC_AGENTS = ROOT / ".opencode" / "agents"
OC_COMMANDS = ROOT / ".opencode" / "commands"

HEADER = "<!-- Generated by testing/build_reviewers.py from testing/reviewers/{src}. Edit the spec, not this file. -->\n"

SUBAGENT_NOTE = (
    "You are running as a subagent with fresh context. Work in one shot: read the files you need, "
    "do the task, and return the requested output. If the material is missing, say exactly what you need and stop.\n\n"
)

ROLEPLAY_AGENT = """This run is one-shot. Do not wait for END and do not ask the user to reply. Treat the material as the consultant's presentation. Reply as the persona in 3 to 6 short turns, each under 120 words, and raise at least three objections or confusions. Then stop the role-play and write the observer report below. Mark anything you had to assume `[assumed]`."""

ROLEPLAY_COMMAND = """Stay in character until the user types END. Keep each reply under 120 words. Ask one question at a time. When the user types END, leave the role and write the observer report below."""

PASTE_FOOTER = """
---
TEAM CONTEXT (paste the contents of testing/context.md here):


MATERIAL (paste the file or text to {verb} here):

"""


def parse(path):
    text = path.read_text()
    _, fm, body = text.split("---\n", 2)
    meta = {}
    for line in fm.strip().splitlines():
        k, v = line.split(":", 1)
        meta[k.strip()] = v.strip()
    return meta, body.strip() + "\n"


def render(body, target, kind, meta):
    """Fill the shared placeholders for one output target."""
    if target == "agent":
        read_context = "First read `testing/context.md` and every file it names. Do not start until you have."
        material = "The material the parent agent passes you. If none is passed, say what you need and stop."
    elif target == "command":
        read_context = "First read `testing/context.md` and every file it names. Do not start until you have."
        material = "$ARGUMENTS (a file path or a short description; if empty, ask me what I am showing you)"
    else:  # paste
        read_context = "The team's context is pasted below under TEAM CONTEXT. Use it as the only source of facts about the project."
        material = "pasted below under MATERIAL"

    text = body.replace("<<READ_CONTEXT>>", read_context).replace("<<MATERIAL>>", material)
    if kind == "roleplay":
        text = text.replace("<<INTERACTION>>", ROLEPLAY_AGENT if target == "agent" else ROLEPLAY_COMMAND)
    return text


def oc_permissions(name):
    """OpenCode V2 permission list. Broad rules first, exceptions last (last match wins)."""
    rules = [("shell", "*", "deny")]
    if name == "test-breaker":
        rules.append(("shell", "Rscript *", "allow"))
    rules.append(("edit", "*", "ask"))
    lines = ["permissions:"]
    for action, resource, effect in rules:
        lines.append(f"  - action: {action}")
        lines.append(f"    resource: {json.dumps(resource)}")
        lines.append(f"    effect: {effect}")
    return "\n".join(lines) + "\n"


def main():
    for d in (AGENTS, COMMANDS, PASTE, OC_AGENTS, OC_COMMANDS):
        d.mkdir(parents=True, exist_ok=True)

    for spec in sorted(SPECS.glob("*.md")):
        meta, body = parse(spec)
        name, kind = meta["name"], meta["kind"]
        src = spec.name
        verb = "review" if kind == "reviewer" else "present"

        # Claude Code subagent. Both reviewers and personas get one.
        agent_body = SUBAGENT_NOTE + render(body, "agent", kind, meta)
        front = (
            f"---\nname: {name}\ndescription: {meta['description']}\n"
            f"tools: {meta['tools']}\nmodel: inherit\n---\n"
        )
        (AGENTS / f"{name}.md").write_text(front + HEADER.format(src=src) + "\n" + agent_body)

        # OpenCode subagent. V2 frontmatter; persona subagents are one-shot.
        oc_front = (
            f"---\ndescription: {meta['description']}\nmode: subagent\n"
            + oc_permissions(name)
            + "---\n"
        )
        (OC_AGENTS / f"{name}.md").write_text(oc_front + HEADER.format(src=src) + "\n" + agent_body)

        if kind == "roleplay":
            # Interactive slash commands stay available for live consulting meetings.
            command_body = render(body, "command", kind, meta)
            cmd_front = (
                f"---\ndescription: {meta['description']}\nargument-hint: [file or note you are presenting]\n"
                f"allowed-tools: {meta['tools']}\n---\n"
            )
            (COMMANDS / f"{name}.md").write_text(cmd_front + HEADER.format(src=src) + "\n" + command_body)
            (OC_COMMANDS / f"{name}.md").write_text(
                f"---\ndescription: {meta['description']}\n---\n" + HEADER.format(src=src) + "\n" + command_body
            )

        # Any chat box: context and material are pasted under the prompt.
        paste_body = render(body, "paste", kind, meta)
        (PASTE / f"{name}.md").write_text(
            HEADER.format(src=src) + "\n" + paste_body + PASTE_FOOTER.format(verb=verb)
        )
        formats = "agent + command + paste" if kind == "roleplay" else "agent + paste"
        print(f"built {name} ({kind}; {formats})")

    # Hand-written commands (not from specs): copy to OpenCode, dropping Claude-only keys.
    for c in ("kickoff", "checkpoint"):
        t = (COMMANDS / f"{c}.md").read_text()
        _, fm, body = t.split("---\n", 2)
        desc = next(l for l in fm.splitlines() if l.startswith("description:"))
        (OC_COMMANDS / f"{c}.md").write_text(f"---\n{desc}\n---\n{body}")
        print(f"copied {c} -> .opencode/commands")


if __name__ == "__main__":
    main()
